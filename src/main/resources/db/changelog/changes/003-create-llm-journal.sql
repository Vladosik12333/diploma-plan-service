CREATE TABLE llm_journal
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_plan_id BIGINT                   NOT NULL,
    type              VARCHAR(20)              NOT NULL,
    provider          VARCHAR(20)              NOT NULL,
    model             VARCHAR(100),
    status            VARCHAR(20)              NOT NULL,
    input_tokens      INT,
    output_tokens     INT,
    duration_ms       BIGINT                   NOT NULL,
    error_message     VARCHAR(500),
    system_prompt     TEXT                     NOT NULL,
    user_prompt       TEXT                     NOT NULL,
    response          TEXT,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_llm_journal_generated_plan FOREIGN KEY (generated_plan_id)
        REFERENCES generated_plans (id) ON DELETE CASCADE
);

CREATE INDEX ix_llm_journal_generated_plan ON llm_journal (generated_plan_id);
