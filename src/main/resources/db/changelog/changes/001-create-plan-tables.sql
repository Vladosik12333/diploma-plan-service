CREATE TABLE generated_plans
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id     BIGINT                   NOT NULL,
    user_id     BIGINT                   NOT NULL,
    status      VARCHAR(20)              NOT NULL,
    provider    VARCHAR(20)              NOT NULL,
    model       VARCHAR(100)             NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_generated_plans_trip ON generated_plans (trip_id, created_at DESC);

CREATE UNIQUE INDEX ux_generated_plans_active ON generated_plans (trip_id)
    WHERE status NOT IN ('DONE', 'FAILED');


CREATE TABLE plan_variants
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_plan_id BIGINT                   NOT NULL,
    type              VARCHAR(20)              NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_plan_variants_generated_plan FOREIGN KEY (generated_plan_id)
        REFERENCES generated_plans (id) ON DELETE CASCADE
);

CREATE INDEX ix_plan_variants_generated_plan ON plan_variants (generated_plan_id);


CREATE TABLE plan_items
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_variant_id        BIGINT                   NOT NULL,
    day_date               DATE                     NOT NULL,
    period                 VARCHAR(20)              NOT NULL,
    position               INT                      NOT NULL,
    name                   VARCHAR(255)             NOT NULL,
    google_place_id        VARCHAR(255),
    category               VARCHAR(64),
    estimated_duration_min INT,
    issue                  VARCHAR(30),
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_plan_items_plan_variant FOREIGN KEY (plan_variant_id)
        REFERENCES plan_variants (id) ON DELETE CASCADE
);

CREATE INDEX ix_plan_items_plan_variant ON plan_items (plan_variant_id);


CREATE TABLE plan_reviews
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_variant_id BIGINT UNIQUE            NOT NULL,
    provider        VARCHAR(20)              NOT NULL,
    model           VARCHAR(100)             NOT NULL,
    preference_fit  INT,
    variety         INT,
    pacing          INT,
    coherence       INT,
    budget_fit      INT,
    overall_score   INT,
    summary         VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_plan_reviews_plan_variant FOREIGN KEY (plan_variant_id)
        REFERENCES plan_variants (id) ON DELETE CASCADE
);
